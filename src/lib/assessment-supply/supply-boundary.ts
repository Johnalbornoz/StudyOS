/** What an evidence record says about where its questions came from. */
export interface SupplyProvenance {
  family: SupplyFamily;
  intent: SupplyIntent;
  itemCategory: ItemCategory;
  source: SupplySource;
}

export function supplyProvenanceOf(intent: SupplyIntent): SupplyProvenance {
  const family = supplyFamilyOf(intent);
  return { family, intent, itemCategory: itemCategoryOf(family), source: supplySourceOf(family) };
}

/** Evidence provenance class of a family (Phase 18): LEARNING | INTERNAL_ASSESSMENT | EXAM_ASSESSMENT. */
export const evidenceClassOf = (family: SupplyFamily): 'LEARNING' | 'INTERNAL_ASSESSMENT' | 'EXAM_ASSESSMENT' => (family === 'STANDARDIZED_EXAM' ? 'EXAM_ASSESSMENT' : family);
