/**
 * THE supply boundary (pure). One place says where a question may come from, for every Student activity.
 *
 *   CURRICULUM + CANONICAL KNOWLEDGE + STUDENT KNOWLEDGE STATE   (the backbone, shared)
 *        |
 *        +-- LEARNING              -> Learning AI Engine             -> LEARNING_ITEM
 *        +-- INTERNAL_ASSESSMENT   -> Internal Assessment Generator  -> INTERNAL_ASSESSMENT_ITEM
 *        +-- STANDARDIZED_EXAM     -> Certified Exam Question Bank   -> EXAM_BANK_ITEM
 *
 * Learning and exam preparation are independent capabilities. Neither needs the other:
 *   - ordinary Learning never depends on Certified Exam Bank inventory;
 *   - a standardized exam never depends on prior StudyUs learning, and its questions are never generated
 *     while a Student is in the product (runtime provider generation = 0).
 *
 * Revised OE-014 (replaces the blanket "Student runtime may not generate questions"):
 *   LEARNING              runtime AI generation ALLOWED, on an explicit command (POST) only
 *   INTERNAL_ASSESSMENT   AI generation ALLOWED BEFORE the attempt begins; the whole assessment is generated,
 *                         validated and frozen first, and nothing is generated during the attempt
 *   STANDARDIZED_EXAM     ZERO runtime generation; insufficient certified content is NOT_READY
 * A GET / page render never generates anything, in any family (OE-011, unchanged).
 *
 * There is deliberately no generic "get questions": a caller states an intent, and the intent names its
 * family, its item category and its one source. Nothing here falls back from one source to another.
 */

export const SUPPLY_FAMILIES = ['LEARNING', 'INTERNAL_ASSESSMENT', 'STANDARDIZED_EXAM'] as const;
export type SupplyFamily = (typeof SUPPLY_FAMILIES)[number];

export type ItemCategory = 'LEARNING_ITEM' | 'INTERNAL_ASSESSMENT_ITEM' | 'EXAM_BANK_ITEM';
export type SupplySource = 'LEARNING_AI_ENGINE' | 'INTERNAL_ASSESSMENT_GENERATOR' | 'CERTIFIED_EXAM_BANK';

/** Explicit supply intents. Every Student activity that needs questions is exactly one of these. */
export const SUPPLY_INTENTS = [
  'LEARNING_PRACTICE', 'LEARNING_RETENTION', 'LEARNING_APPLICATION',
  'INTERNAL_DIAGNOSTIC', 'INTERNAL_MASTERY_CHECK', 'INTERNAL_AD_HOC',
  'EXAM_PRACTICE', 'EXAM_REDUCED_MOCK', 'EXAM_FULL_MOCK', 'EXAM_CHALLENGE',
] as const;
export type SupplyIntent = (typeof SUPPLY_INTENTS)[number];

export const SUPPLY_FAMILY_OF_INTENT: Record<SupplyIntent, SupplyFamily> = {
  LEARNING_PRACTICE: 'LEARNING', LEARNING_RETENTION: 'LEARNING', LEARNING_APPLICATION: 'LEARNING',
  INTERNAL_DIAGNOSTIC: 'INTERNAL_ASSESSMENT', INTERNAL_MASTERY_CHECK: 'INTERNAL_ASSESSMENT', INTERNAL_AD_HOC: 'INTERNAL_ASSESSMENT',
  EXAM_PRACTICE: 'STANDARDIZED_EXAM', EXAM_REDUCED_MOCK: 'STANDARDIZED_EXAM', EXAM_FULL_MOCK: 'STANDARDIZED_EXAM', EXAM_CHALLENGE: 'STANDARDIZED_EXAM',
};

const BOUNDARY: Record<SupplyFamily, { itemCategory: ItemCategory; source: SupplySource }> = {
  LEARNING: { itemCategory: 'LEARNING_ITEM', source: 'LEARNING_AI_ENGINE' },
  INTERNAL_ASSESSMENT: { itemCategory: 'INTERNAL_ASSESSMENT_ITEM', source: 'INTERNAL_ASSESSMENT_GENERATOR' },
  STANDARDIZED_EXAM: { itemCategory: 'EXAM_BANK_ITEM', source: 'CERTIFIED_EXAM_BANK' },
};

export const supplyFamilyOf = (intent: SupplyIntent): SupplyFamily => SUPPLY_FAMILY_OF_INTENT[intent];
export const itemCategoryOf = (family: SupplyFamily): ItemCategory => BOUNDARY[family].itemCategory;
export const supplySourceOf = (family: SupplyFamily): SupplySource => BOUNDARY[family].source;

/** When, in the life of an activity, a provider may be asked for its questions. */
export type GenerationMoment = 'PAGE_RENDER' | 'EXPLICIT_COMMAND' | 'DURING_ATTEMPT';

/**
 * May questions be generated by a provider for this family at this moment?
 * A page render never generates. A standardized exam never generates. Learning generates on an explicit
 * command, including the next activity of a session; an internal assessment generates only before it starts.
 */
export function providerGenerationAllowed(family: SupplyFamily, moment: GenerationMoment): boolean {
  if (moment === 'PAGE_RENDER') return false;
  if (family === 'STANDARDIZED_EXAM') return false;
  if (family === 'INTERNAL_ASSESSMENT') return moment === 'EXPLICIT_COMMAND';
  return moment === 'EXPLICIT_COMMAND' || moment === 'DURING_ATTEMPT';
}

/** Does insufficient content of the family's own source block the activity (NOT_READY), or is it produced on demand? */
export const insufficientSupplyIs = (family: SupplyFamily): 'GENERATED_ON_DEMAND' | 'NOT_READY' => (family === 'STANDARDIZED_EXAM' ? 'NOT_READY' : 'GENERATED_ON_DEMAND');

