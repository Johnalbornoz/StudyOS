export type RosterMessageKey = keyof typeof es;
export const ROSTER_MESSAGES: Record<Locale, Catalog> = { es, en, de, fr, pt };

export function rosterMessages(locale: string | null | undefined): Record<string, string> {
  return ROSTER_MESSAGES[(locale ?? 'es') as Locale] ?? ROSTER_MESSAGES.es;
}

export function fillRosterMessage(template: string | undefined, vars: Record<string, string | number>): string {
  return Object.entries(vars).reduce((acc, [k, v]) => acc.replace(`{${k}}`, String(v)), template ?? '');
}
